export function getPropertyBySlug(slug: string) {
  return MOCK_PROPERTIES.find((p) => p.slug === slug);
}

export function getPropertiesByCategory(category: string) {
  if (category === "recommended") {
    return [...MOCK_PROPERTIES].sort((a, b) => b.rating - a.rating).slice(0, 8);
  }
  return MOCK_PROPERTIES.filter((p) => p.categories.includes(category as Property["categories"][number]));
}

export function filterProperties(params: {
  q?: string;
  purpose?: PropertyPurpose | "all";
  minPrice?: number;
  maxPrice?: number;
  bedrooms?: number;
  bathrooms?: number;
  minArea?: number;
  type?: string;
  furnished?: "all" | "yes" | "no";
}) {
  return MOCK_PROPERTIES.filter((p) => {
    if (params.purpose && params.purpose !== "all" && p.purpose !== params.purpose) return false;
    if (params.minPrice != null && p.price < params.minPrice) return false;
    if (params.maxPrice != null && p.price > params.maxPrice) return false;
    if (params.bedrooms != null && params.bedrooms > 0 && p.bedrooms < params.bedrooms) return false;
    if (params.bathrooms != null && params.bathrooms > 0 && p.bathrooms < params.bathrooms) return false;
    if (params.minArea != null && p.areaSqm < params.minArea) return false;
    if (params.type && params.type !== "all" && !p.categories.includes(params.type as never)) return false;
    if (params.furnished === "yes" && !p.furnished) return false;
    if (params.furnished === "no" && p.furnished) return false;
    if (params.q) {
      const q = params.q.toLowerCase();
      const hay = `${p.title} ${p.city} ${p.address}`.toLowerCase();
      if (!hay.includes(q)) return false;
    }
    return true;
  });
}
